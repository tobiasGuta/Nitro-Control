"""Per-user dashboard deployment and optional tray login entry."""

from __future__ import annotations

import argparse
import ast
import fcntl
import hashlib
import json
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile
from contextlib import contextmanager
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1]
APP_ID = "io.github.tobiasguta.NitroControl"
GUI_MARKER = b"Nitro Control per-user deployment v1\n"
TRAY_MARKER = "# Managed by Nitro Control optional tray autostart"
LAUNCHER = b"""#!/usr/bin/python3 -IB
import runpy
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
runpy.run_module("nitro_control", run_name="__main__", alter_sys=True)
"""
LEGACY_LAUNCHER = b"""#!/usr/bin/env bash
set -euo pipefail
# Do not import an outdated nitro_control package from the caller's cwd.
app_dir="$HOME/.local/share/nitro-control"
cd -- "$app_dir"
export PYTHONPATH="$app_dir${PYTHONPATH:+:$PYTHONPATH}"
# -P prevents Python from prepending an unsafe cwd to sys.path (Python 3.11+).
exec /usr/bin/python3 -P -m nitro_control "$@"
"""
LIVE = f"{APP_ID}.desktop"
DEMO = f"{APP_ID}.Demo.desktop"
TRAY = f"{APP_ID}.Tray.desktop"
ICON = f"icons/hicolor/scalable/apps/{APP_ID}.svg"
SYMBOLIC = f"icons/hicolor/symbolic/apps/{APP_ID}-symbolic.svg"
PUBLIC = {
    f"share/applications/{LIVE}": LIVE,
    f"share/applications/{DEMO}": DEMO,
    f"share/{ICON}": Path(ICON).name,
    f"share/{SYMBOLIC}": Path(SYMBOLIC).name,
    "bin/nitro-control": "nitro-control",
}
RELEASE_NAME = re.compile(r"release-[a-f0-9]{64}\Z")
# Core modules shared by the dashboard, CLI, and tray in supported rollback sources.
ESSENTIAL_MODULES = frozenset({
    "__init__", "__main__", "demo", "hardware", "models", "ui", "dashboard_visuals",
    "fan_control", "fan_client", "profiles", "rgb", "rgb_client", "rgb_hardware",
    "tray_indicator", "tray_model", "tray_preferences",
})



def _desktop(mode: str, command: str, *, icon: str = APP_ID) -> bytes:
    # The command is generated by us. The caller never supplies desktop syntax.
    if mode == "tray":
        header = f"{TRAY_MARKER}\n"
        name = "Nitro Control Tray"
        comment = "Comment=Optional read-only hardware monitoring indicator\n"
        extra = "OnlyShowIn=GNOME;\nX-GNOME-Autostart-enabled=true\n"
    elif mode == "demo":
        header, name, comment = "", "Nitro Control (Demo)", ""
        extra = "NoDisplay=true\nStartupNotify=true\n"
    else:
        header, name = "", "Nitro Control"
        comment = "Comment=Acer Nitro dashboard and desktop power modes\n"
        extra = "Categories=System;Monitor;GTK;\nStartupNotify=true\n"
    return (f"{header}[Desktop Entry]\nType=Application\nName={name}\n{comment}"
            f"Exec={command}\nIcon={icon}\nTerminal=false\n{extra}").encode()


def _desktop_command(mode: str) -> str:
    # Keep Exec ASCII and free of interpolated paths and field codes. The
    # fixed Python command passes the home-relative launcher directly to exec.
    command = ('/usr/bin/python3 -I -c "import os,sys; from pathlib import Path; '
               "p = str(Path.home() / '.local/bin/nitro-control'); "
               'os.execv(p, [p] + sys.argv[1:])"')
    return command + (f" --{mode}" if mode else "")


def _version(source: Path) -> str:
    return _parse_version((source / "nitro_control/__init__.py").read_bytes())


def _parse_version(data: bytes) -> str:
    init = ast.parse(data)
    for node in init.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__version__" for target in node.targets
        ):
            version = ast.literal_eval(node.value)
            if isinstance(version, str):
                return version
    raise ValueError("Source package has no version")


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _mode(path: Path) -> int | None:
    try:
        return path.lstat().st_mode
    except FileNotFoundError:
        return None


def _regular_matches(path: Path, mode: int, digest: str) -> bool:
    info = _mode(path)
    return (info is not None and stat.S_ISREG(info) and stat.S_IMODE(info) == mode
            and _sha(path.read_bytes()) == digest)


def _manifest(files: dict[str, tuple[int, bytes]]) -> bytes:
    return json.dumps({name: [mode, _sha(data)] for name, (mode, data) in files.items()},
                      sort_keys=True, separators=(",", ":")).encode()


def _package(source: Path) -> dict[str, tuple[int, bytes]]:
    package = source / "nitro_control"
    if package.is_symlink() or not package.is_dir():
        raise ValueError("Source package must be a directory")
    files = {}
    for path in package.rglob("*"):
        if "__pycache__" in path.relative_to(package).parts or path.suffix in {".pyc", ".pyo"}:
            continue
        if path.is_symlink() or not (path.is_dir() or path.is_file()):
            raise ValueError(f"Unsupported package entry {path}")
        if path.is_file():
            files[path.relative_to(source).as_posix()] = (0o644, path.read_bytes())
    modules = {Path(name).stem for name in files if Path(name).parent == Path("nitro_control")
               and name.endswith(".py")}
    missing = ESSENTIAL_MODULES - modules
    if missing:
        raise ValueError(f"Incomplete Nitro Control package. Missing {', '.join(sorted(missing))}")
    for name, (_, data) in files.items():
        if not name.endswith(".py"):
            continue
        compile(data, name, "exec")
        if Path(name).parent == Path("nitro_control"):
            for node in ast.walk(ast.parse(data, filename=name)):
                if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
                    dependency = node.module.split(".", 1)[0]
                    if dependency not in modules and f"nitro_control/{dependency}/__init__.py" not in files:
                        raise ValueError(f"Incomplete Nitro Control package. {name} imports missing {dependency}")
    _parse_version(files["nitro_control/__init__.py"][1])
    return files


def _write(path: Path, data: bytes, mode: int) -> None:
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".nitro-control-", delete=False) as out:
        tmp = Path(out.name)
        try:
            out.write(data)
            out.flush()
            os.fchmod(out.fileno(), mode)
            os.fsync(out.fileno())
            os.replace(tmp, path)
        finally:
            tmp.unlink(missing_ok=True)


def _link(path: Path, target: str) -> None:
    with tempfile.TemporaryDirectory(dir=path.parent, prefix=".nitro-control-") as directory:
        tmp = Path(directory) / "link"
        tmp.symlink_to(target)
        os.replace(tmp, path)


class Deployment:
    def __init__(self, home: Path, config: Path):
        self.home = home
        self.app = home / ".local/share/nitro-control"
        self.store = self.app / "deployment"
        self.current = self.store / "current"
        self.launcher = home / ".local/bin/nitro-control"
        self.tray = config / "autostart" / TRAY

    def _directories(self, path: Path, *, create: bool = False) -> None:
        # Check every component below the selected home/config root. Public
        # links may be symlinks; their containing directories must be real.
        base = self.home if path.is_relative_to(self.home) else Path(path.anchor)
        for parent in reversed(path.relative_to(base).parents):
            self._directory(base / parent, create)
        self._directory(path, create)

    @staticmethod
    def _directory(path: Path, create: bool) -> None:
        info = _mode(path)
        if info is None and create:
            path.mkdir(exist_ok=True)
            info = path.lstat().st_mode
        if info is not None and not stat.S_ISDIR(info):
            raise ValueError(f"Expected a directory at {path}")

    @contextmanager
    def _lock(self):
        # The home directory inode exists before first install and remains
        # after uninstall. Every mutating entry point uses the same lock.
        fd = os.open(self.home, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX)
            yield
        finally:
            os.close(fd)

    def _managed_store(self, *, create: bool = False) -> bool:
        self._directory(self.store, False)
        if not self.store.exists() or not any(self.store.iterdir()):
            if not create:
                return False
            # Publish the namespace and ownership marker together. An
            # interruption during bootstrap cannot leave an unusable store.
            with tempfile.TemporaryDirectory(dir=self.app, prefix=".deployment-") as directory:
                stage = Path(directory)
                marker = stage / "owner"
                marker.write_bytes(GUI_MARKER)
                marker.chmod(0o644)
                stage.rename(self.store)
        owner = self.store / "owner"
        if not _regular_matches(owner, 0o644, _sha(GUI_MARKER)):
            raise ValueError(f"Unrecognized deployment directory {self.store}")
        return True

    def _active_release(self) -> str | None:
        if _mode(self.current) is None:
            return None
        if not self.current.is_symlink():
            raise ValueError(f"Unrecognized activation link {self.current}")
        target = os.readlink(self.current)
        if not RELEASE_NAME.fullmatch(target):
            raise ValueError(f"Unrecognized activation link {self.current}")
        return target

    def _manifest_entries(self, release: Path) -> dict[str, tuple[int, str]]:
        self._directory(release, False)
        manifest = release / "manifest.json"
        data = manifest.read_bytes() if not manifest.is_symlink() and manifest.is_file() else b""
        if release.name != f"release-{_sha(data)}":
            raise ValueError(f"Unrecognized release manifest {manifest}")
        entries = json.loads(data)
        if not isinstance(entries, dict) or not set(PUBLIC.values()).issubset(entries):
            raise ValueError(f"Incomplete release manifest {manifest}")
        for name, value in entries.items():
            relative = Path(name)
            if (relative.is_absolute() or ".." in relative.parts or relative.as_posix() != name or
                    (name not in PUBLIC.values() and relative.parts[:1] != ("nitro_control",)) or
                    not isinstance(value, list) or len(value) != 2 or value[0] not in (0o644, 0o755) or
                    not isinstance(value[1], str) or not re.fullmatch("[0-9a-f]{64}", value[1])):
                raise ValueError(f"Invalid release manifest {manifest}")
        return entries

    def _check_release(self, release: Path) -> None:
        entries = self._manifest_entries(release)
        expected_files = set(entries) | {"manifest.json"}
        expected_dirs = {parent.as_posix() for name in entries for parent in Path(name).parents} - {"."}
        for path in release.rglob("*"):
            name = path.relative_to(release).as_posix()
            if path.is_symlink() or name not in (expected_dirs if path.is_dir() else expected_files):
                raise ValueError(f"Unexpected file in release {path}")
        for name, (mode, digest) in entries.items():
            if not _regular_matches(release / name, mode, digest):
                raise ValueError(f"Modified or missing release file {release / name}")

    def _target(self, path: Path, name: str) -> str:
        return os.path.relpath(self.current / name, path.parent)

    def _legacy(self, path: Path, name: str) -> bool:
        if name == "nitro-control":
            candidates, mode = [LEGACY_LAUNCHER], 0o755
        elif name == LIVE:
            candidates = [_desktop("", str(self.launcher), icon=icon)
                          for icon in (APP_ID, "utilities-system-monitor")]
            mode = 0o644
        elif name == DEMO:
            candidates, mode = [_desktop("demo", f"{self.launcher} --demo")], 0o644
        else:
            icon = ICON if name == Path(ICON).name else SYMBOLIC
            candidates, mode = [(SOURCE / "nitro_control" / icon).read_bytes()], 0o644
        return any(_regular_matches(path, mode, _sha(data)) for data in candidates)

    def _publication(self, *, managed: bool, remove: bool = False):
        for relative, name in PUBLIC.items():
            path = self.home / ".local" / relative
            self._directories(path.parent)
            info = _mode(path)
            target = self._target(path, name)
            if managed and path.is_symlink() and os.readlink(path) == target:
                yield path, target, True
            elif info is None or self._legacy(path, name):
                yield path, target, False
            elif remove:
                print(f"Preserving unrecognized artifact {path}", file=sys.stderr)
            else:
                raise ValueError(f"Refusing to replace unrecognized artifact {path}")

    def install(self, source: Path) -> None:
        files = _package(source)
        files.update({LIVE: (0o644, _desktop("", _desktop_command(""))),
                      DEMO: (0o644, _desktop("demo", _desktop_command("demo"))),
                      "nitro-control": (0o755, LAUNCHER)})
        for icon in (ICON, SYMBOLIC):
            data = files.get(f"nitro_control/{icon}")
            files[Path(icon).name] = data or (0o644, (SOURCE / "nitro_control" / icon).read_bytes())
        manifest = _manifest(files)
        with self._lock():
            self._directories(self.app, create=True)
            # Refuse collisions before replacing public files or selecting a release.
            managed = self._managed_store()
            public = list(self._publication(managed=managed))
            self._managed_store(create=True)
            active = self._active_release()
            if active is not None:
                self._check_release(self.store / active)
            release = self.store / f"release-{_sha(manifest)}"
            if _mode(release) is None:
                with tempfile.TemporaryDirectory(dir=self.store, prefix="staging-") as directory:
                    stage = Path(directory)
                    for name, (mode, data) in files.items():
                        path = stage / name
                        path.parent.mkdir(parents=True, exist_ok=True)
                        path.write_bytes(data)
                        path.chmod(mode)
                    (stage / "manifest.json").write_bytes(manifest)
                    stage.rename(release)
            else:
                self._check_release(release)
            # The first activation must exist before publishing any links.
            # Subsequent releases become visible through a single link change.
            if active is None:
                _link(self.current, release.name)
            for path, target, already_linked in public:
                if not already_linked:
                    self._directories(path.parent, create=True)
                    _link(path, target)
            if active is not None and active != release.name:
                _link(self.current, release.name)
        self._refresh_desktop_caches()
        print("Installed Nitro Control for this user.")

    def _remove_release(self, release: Path) -> None:
        entries = self._manifest_entries(release)
        parents = {parent for name in entries for parent in (release / name).parents
                   if parent.is_relative_to(release)}
        for name, (mode, digest) in entries.items():
            path = release / name
            # A modified directory or symlink may contain unrelated files.
            if any(parent.is_symlink() for parent in path.parents if parent.is_relative_to(release)):
                continue
            if _regular_matches(path, mode, digest):
                path.unlink()
        for parent in sorted(parents - {release}, key=lambda path: -len(path.parts)):
            if any(path.is_symlink() for path in (parent, *parent.parents) if path.is_relative_to(release)):
                continue
            if parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
        if sorted(path.name for path in release.iterdir()) == ["manifest.json"]:
            (release / "manifest.json").unlink()
            release.rmdir()
        else:
            print(f"Preserving files in {release}", file=sys.stderr)

    def uninstall(self) -> None:
        with self._lock():
            self._directories(self.app)
            managed = self._managed_store()
            active = self._active_release() if managed else None
            for path, _, owned_link in reversed(list(self._publication(managed=managed, remove=True))):
                if owned_link or path.is_file():
                    path.unlink()
            self._disable_tray_locked()
            if managed:
                if active is not None:
                    self.current.unlink()
                for release in self.store.iterdir():
                    if RELEASE_NAME.fullmatch(release.name):
                        try:
                            self._remove_release(release)
                        except (OSError, ValueError) as exc:
                            print(f"Preserving {release}. {exc}", file=sys.stderr)
                owner = self.store / "owner"
                if list(self.store.iterdir()) == [owner]:
                    owner.unlink()
                    self.store.rmdir()
        self._refresh_desktop_caches()
        print("Nitro Control user installation removed. User preferences were preserved.")

    def _owned_tray(self, path: Path) -> bool:
        candidates = [_desktop("tray", _desktop_command("tray"))]
        if not any(character in str(self.launcher) for character in ('"', '\\', '\n')):
            candidates.append(_desktop("tray", f'"{self.launcher}" --tray'))
        return any(_regular_matches(path, 0o644, _sha(data)) for data in candidates)

    def _check_tray_launcher(self) -> None:
        self._directories(self.launcher.parent)
        self._directories(self.app)
        if not self._managed_store():
            if not self._legacy(self.launcher, "nitro-control"):
                raise ValueError(f"Unrecognized tray launcher {self.launcher}")
            _package(self.app)
            return

        active = self._active_release()
        if (active is None or not self.launcher.is_symlink() or
                os.readlink(self.launcher) != self._target(self.launcher, "nitro-control")):
            raise ValueError(f"Incomplete deployment or unrecognized tray launcher {self.launcher}")
        self._check_release(self.store / active)
        if not _regular_matches(self.store / active / "nitro-control", 0o755, _sha(LAUNCHER)):
            raise ValueError("Unrecognized launcher in selected Nitro Control release")
        _package(self.store / active)

    def enable_tray(self) -> None:
        with self._lock():
            self._check_tray_launcher()
            self._enable_tray_locked()

    def _enable_tray_locked(self) -> None:
        self._directories(self.tray.parent)
        if _mode(self.tray) is not None and not self._owned_tray(self.tray):
            raise ValueError(f"Refusing to replace unrecognized autostart file {self.tray}")
        self._directories(self.tray.parent, create=True)
        _write(self.tray, _desktop("tray", _desktop_command("tray")), 0o644)
        print("Nitro Control tray autostart enabled for the next GNOME login.")

    def disable_tray(self) -> bool:
        with self._lock():
            return self._disable_tray_locked()

    def _disable_tray_locked(self) -> bool:
        clean = True
        default = self.home / ".config/autostart" / TRAY
        for path in dict.fromkeys((self.tray, default)):
            try:
                self._directories(path.parent)
                if _mode(path) is None:
                    continue
                if self._owned_tray(path):
                    path.unlink()
                    print("Nitro Control tray autostart disabled.")
                    continue
            except ValueError as exc:
                print(exc, file=sys.stderr)
            print(f"Preserving unrecognized autostart file {path}", file=sys.stderr)
            clean = False
        return clean

    def _refresh_desktop_caches(self) -> None:
        for program, args, relative in (("gtk-update-icon-cache", ["-f", "-t", "-q"], "icons/hicolor"),
                                        ("update-desktop-database", ["-q"], "applications")):
            directory = self.home / ".local/share" / relative
            if shutil.which(program) and directory.is_dir():
                try:
                    self._directories(directory)
                    subprocess.run([program, *args, str(directory)], check=False, timeout=10,
                                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                except (OSError, ValueError, subprocess.TimeoutExpired):
                    pass


def main() -> int:
    action, script, *args = sys.argv[1:]
    parser = argparse.ArgumentParser(prog=script, add_help=False, allow_abbrev=False)
    info = parser.add_mutually_exclusive_group()
    info.add_argument("-h", "--help", action="store_true", help="show usage and exit")
    info.add_argument("--version", action="store_true", help="show package version and exit")
    if action == "install":
        parser.add_argument("--source", type=Path, default=SOURCE, help="install a reviewed source tree")
    options = parser.parse_args(args)
    if options.help:
        parser.print_help()
        return 0
    if options.version:
        print(f"Nitro Control {_version(SOURCE)}")
        return 0
    if action in {"enable-tray", "disable-tray"} and os.geteuid() == 0:
        parser.error("run tray autostart commands as your regular user")
    try:
        home = Path.home().resolve(strict=True)
        if not home.is_dir():
            raise ValueError(f"Invalid home directory {home}")
        config = Path(os.environ.get("XDG_CONFIG_HOME", ""))
        if not config.is_absolute():
            config = home / ".config"
        else:
            config = Path(os.path.abspath(config))
        deployment = Deployment(home, config)
        if action == "install":
            if subprocess.run(
                ["/usr/bin/python3", "-IB", "-c",
                 'import cairo,gi; gi.require_version("Gtk","4.0"); gi.require_version("Adw","1"); '
                 'gi.require_foreign("cairo"); from gi.repository import Gtk,Adw'],
                check=False, capture_output=True, timeout=15,
            ).returncode:
                raise ValueError("Missing GUI dependencies (Fedora packages python3-gobject python3-cairo gtk4 libadwaita)")
            deployment.install(options.source.resolve(strict=True))
        elif action == "uninstall":
            deployment.uninstall()
        elif action == "enable-tray":
            deployment.enable_tray()
        elif not deployment.disable_tray():
            return 1
    except (OSError, ValueError, SyntaxError, subprocess.TimeoutExpired) as exc:
        print(f"Nitro Control deployment failed. {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
